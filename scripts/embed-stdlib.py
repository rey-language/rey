#!/usr/bin/env python3
"""Generate or check the embedded std/src Rey standard library module.

Run before building a standalone compiler so its std imports do not depend on
an installed Rey toolchain.
"""
import argparse
from pathlib import Path
import sys


CHUNK_CHARS = 192
PART_CHARS = 8192


def quote_text(data: str) -> str:
    parts = ['"']
    for char in data:
        value = ord(char)
        if char == '"':
            parts.append('\\"')
        elif char == "\\":
            parts.append('\\\\')
        elif char == "{":
            parts.append('\\x7B')
        elif char == "}":
            parts.append('\\x7D')
        elif char == "\n":
            parts.append('\\n')
        elif char == "\r":
            parts.append('\\r')
        elif char == "\t":
            parts.append('\\t')
        elif value >= 0x20 and value != 0x7F:
            parts.append(char)
        else:
            parts.append(f"\\x{value:02X}")
    parts.append('"')
    return "".join(parts)


def concat_expression(literals: list[str]) -> str:
    if len(literals) == 1:
        return literals[0]
    middle = len(literals) // 2
    left = concat_expression(literals[:middle])
    right = concat_expression(literals[middle:])
    return "(" + left + " +\n    " + right + ")"


def render(root: Path) -> str:
    std_root = root / "std" / "src"
    files = sorted(std_root.rglob("*.rey"))
    if not files:
        raise SystemExit(f"no standard-library Rey sources found under {std_root}")

    lines = [
        "// generated by scripts/embed-stdlib.py from std/src/**/*.rey.",
        "// regenerate before building standalone compiler stages after stdlib edits.",
        "import frontend::graph::{EmbeddedSource};",
        "",
        'pub func embeddedStdRoot(): string { return "/__rey_embedded_stdlib/std"; }',
        "",
    ]
    for index, path in enumerate(files):
        data = path.read_text(encoding="utf-8")
        source_parts = [data[offset : offset + PART_CHARS] for offset in range(0, len(data), PART_CHARS)]
        if not source_parts:
            source_parts = [""]
        part_calls = []
        for part_index, source_part in enumerate(source_parts):
            chunks = [source_part[offset : offset + CHUNK_CHARS] for offset in range(0, len(source_part), CHUNK_CHARS)]
            if not chunks:
                chunks = [""]
            literals = [quote_text(chunk) for chunk in chunks]
            part_name = f"embeddedStdSource{index}Part{part_index}"
            lines.append(f"func {part_name}(): string {{")
            lines.append("    return " + concat_expression(literals) + ";")
            lines.append("}")
            lines.append("")
            part_calls.append(part_name + "()")
        lines.append(f"func embeddedStdSource{index}(): string {{")
        lines.append("    return " + concat_expression(part_calls) + ";")
        lines.append("}")
        lines.append("")

    lines.extend([
        "pub func embeddedStdSources(): Vec<EmbeddedSource> {",
        "    var root = embeddedStdRoot();",
        "    var sources: Vec<EmbeddedSource> = [];",
    ])
    for index, path in enumerate(files):
        relative = path.relative_to(std_root).as_posix()
        lines.append(
            f'    sources.push(EmbeddedSource {{ path: root + "/src/{relative}", source: embeddedStdSource{index}() }});'
        )
    lines.extend(["    return sources;", "}", ""])
    return "\n".join(lines)


def main() -> int:
    script_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=script_root, help="repository root")
    parser.add_argument(
        "--output",
        type=Path,
        default=script_root / "rey-compiler/src/frontend/embedded_stdlib/main.rey",
        help="generated Rey module path",
    )
    parser.add_argument("--check", action="store_true", help="fail if the generated module is stale")
    args = parser.parse_args()
    expected = render(args.root.resolve()).encode("utf-8")
    output = args.output.resolve()
    if args.check:
        if not output.is_file() or output.read_bytes() != expected:
            print("error: embedded stdlib is stale; run python3 scripts/embed-stdlib.py", file=sys.stderr)
            return 1
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
