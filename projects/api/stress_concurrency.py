#!/usr/bin/env python3
import concurrent.futures
import json
import os
import subprocess
import sys
import time
import urllib.request
import urllib.error

PORT = 8085
BASE_URL = f"http://localhost:{PORT}"

def reset_db():
    print("[Setup] Resetting database...")
    subprocess.run(["psql", "-d", "rey_social_db", "-f", "schema.sql"], capture_output=True, check=True)
    time.sleep(0.5)

def create_user_worker(user_idx):
    url = f"{BASE_URL}/api/users"
    payload = json.dumps({
        "username": f"stress_user_{user_idx}_{int(time.time()*1000)}",
        "name": f"Stress Tester #{user_idx}",
        "bio": "Generated by stress test runner"
    }).encode("utf-8")

    req = urllib.request.Request(
        url,
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST"
    )

    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = resp.read().decode("utf-8")
            elapsed = time.time() - t0
            return (resp.status, elapsed, data, None)
    except urllib.error.HTTPError as e:
        elapsed = time.time() - t0
        body = e.read().decode("utf-8", errors="replace")
        return (e.code, elapsed, body, f"HTTPError {e.code}: {body}")
    except Exception as e:
        elapsed = time.time() - t0
        return (0, elapsed, "", str(e))

def run_concurrency_tier(concurrency):
    print(f"\n--- Testing Concurrency Level: {concurrency} concurrent requests ---")
    start = time.time()
    results = []

    with concurrent.futures.ThreadPoolExecutor(max_workers=concurrency) as executor:
        futures = [executor.submit(create_user_worker, i) for i in range(concurrency)]
        for f in concurrent.futures.as_completed(futures):
            results.append(f.result())

    total_time = time.time() - start

    successes = [r for r in results if r[0] == 201]
    failures = [r for r in results if r[0] != 201]

    latencies = [r[1] for r in results]
    avg_latency = sum(latencies) / len(latencies) if latencies else 0

    print(f"Total Requests: {concurrency}")
    print(f"Success Count:  {len(successes)} ({len(successes)/concurrency*100:.1f}%)")
    print(f"Failure Count:  {len(failures)} ({len(failures)/concurrency*100:.1f}%)")
    print(f"Total Duration: {total_time:.2f}s (Throughput: {len(successes)/total_time:.1f} req/s)")
    print(f"Avg Latency:    {avg_latency*1000:.1f}ms")

    if failures:
        print("Failure Samples:")
        error_types = {}
        for f in failures:
            msg = f[3] or f[2] or f"Status {f[0]}"
            # Truncate long messages
            short_msg = msg[:120].replace("\n", " ")
            error_types[short_msg] = error_types.get(short_msg, 0) + 1
        for msg, count in list(error_types.items())[:5]:
            print(f"  [{count}x] {msg}")

    return len(failures) == 0

def main():
    reset_db()

    env = os.environ.copy()
    env["PORT"] = str(PORT)
    server_proc = subprocess.Popen(["node", "server.js"], env=env)

    print(f"Waiting for server to start on port {PORT}...")
    for _ in range(30):
        try:
            with urllib.request.urlopen(f"{BASE_URL}/api/health", timeout=1) as resp:
                if resp.status == 200:
                    print("Server online!")
                    break
        except Exception:
            time.sleep(0.2)
    else:
        print("Server failed to start!")
        server_proc.kill()
        sys.exit(1)

    try:
        tiers = [5, 10, 25, 50, 75, 100, 120, 150, 200]
        failed_tier = None
        for c in tiers:
            ok = run_concurrency_tier(c)
            if not ok and failed_tier is None:
                failed_tier = c
                print(f"\n=> FIRST CONCURRENCY FAILURE DETECTED AT: {c} concurrent requests!")
            # Small cooldown between tiers
            time.sleep(1.0)

        if failed_tier:
            print(f"\n=======================================================")
            print(f" BREAKING POINT: Server / Database failed at {failed_tier} concurrent users.")
            print(f"=======================================================")
        else:
            print(f"\nAll concurrency tiers up to {tiers[-1]} passed!")
    finally:
        server_proc.terminate()
        server_proc.wait()

if __name__ == "__main__":
    main()
